function resolveInitialLanguage(): AppLanguage {
  if (typeof window === "undefined") {
    return "en";
  }
  const stored = window.localStorage.getItem(LANGUAGE_KEY);
  const normalizedStored = normalizeLanguage(stored);
  if (normalizedStored) {
    setDocumentLanguage(normalizedStored);
    return normalizedStored;
  }
  const nav = normalizeLanguage(window.navigator.language);
  const initial = nav ?? "en";
  window.localStorage.setItem(LANGUAGE_KEY, initial);
  setDocumentLanguage(initial);
  return initial;
}

function normalizeLanguage(raw: unknown): AppLanguage | null {
  const value = String(raw ?? "").trim().toLowerCase();
  if (value.startsWith("bn")) {
    return "bn";
  }
  if (value.startsWith("en")) {
    return "en";
  }
  return null;
}

function setDocumentLanguage(language: AppLanguage) {
  if (typeof document !== "undefined") {
    document.documentElement.lang = language;
  }
}

function interpolate(template: string, params?: Record<string, string | number>) {
  if (!params) {
    return template;
  }
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
}

export function getLanguage(): AppLanguage {
  return currentLanguage.value;
}

export function setLanguage(raw: unknown): AppLanguage {
  const next = normalizeLanguage(raw) ?? "en";
  if (currentLanguage.value === next) {
    return next;
  }
  currentLanguage.value = next;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(LANGUAGE_KEY, next);
  }
  setDocumentLanguage(next);
  return next;
}

export function toggleLanguage(): AppLanguage {
  return setLanguage(currentLanguage.value === "en" ? "bn" : "en");
}

export function t(key: string, params?: Record<string, string | number>): string {
  const template = currentLanguage.value === "bn" ? (bnMessages[key] ?? key) : key;
  return interpolate(template, params);
}

export function translateEnum(value: string): string {
  const key = `enum.${value}`;
  const translated = t(key);
  if (translated !== key) {
    return translated;
  }
  return value.replaceAll("_", " ");
}

export function formatMoney(value: number): string {
  const locale = currentLanguage.value === "bn" ? "bn-BD" : "en-BD";
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "BDT",
    minimumFractionDigits: 2
  }).format(value ?? 0);
}

export function monthYearLabel(month: string): string {
  const [year, monthNum] = month.split("-").map(Number);
  if (!year || !monthNum) {
    return month;
  }
  const locale = currentLanguage.value === "bn" ? "bn-BD" : "en-US";
  return new Date(year, monthNum - 1, 1).toLocaleString(locale, { month: "short", year: "numeric" });
}

export function useI18n() {
  return {
    language: readonly(currentLanguage),
    isBangla: computed(() => currentLanguage.value === "bn"),
    setLanguage,
    toggleLanguage,
    t,
    translateEnum,
    formatMoney,
    monthYearLabel
  };
}
